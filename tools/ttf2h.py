#!/usr/bin/env python3
"""
FluxKit font converter: .ttf/.otf  ->  C++ source you can compile into your project.

  python tools/ttf2h.py Inter-Bold.ttf                       # -> Inter_Bold.h  (header-only, include it)
  python tools/ttf2h.py Inter-Bold.ttf --subset latin        # shrink to Latin (needs: pip install fonttools)
  python tools/ttf2h.py Noto.ttf --subset "U+0020-007E,U+0400-04FF"   # custom Unicode ranges
  python tools/ttf2h.py font.ttf --name myfont --cpp         # -> myfont.cpp with extern symbols (used by FluxKit built-ins)

In your sketch:
  #include "Inter_Bold.h"
  auto inter = fk::FontFace::fromMemory(Inter_Bold_ttf, Inter_Bold_ttf_len, "Inter");
  fk::registerFont("Inter", inter);
"""
import argparse, os, re, subprocess, sys, tempfile

LATIN = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+2013-2014,U+2018-201E,U+2022,U+2039-203A,U+2026,U+20AC,U+2122,U+2190-2193,U+2212"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("--name", help="C identifier prefix (default: file name)")
    ap.add_argument("--subset", help="'latin' or a pyftsubset unicode list")
    ap.add_argument("--cpp", action="store_true", help="emit a .cpp with extern declarations instead of a header")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()

    src = a.font
    if a.subset:
        unicodes = LATIN if a.subset == "latin" else a.subset
        tmp = tempfile.NamedTemporaryFile(suffix=os.path.splitext(src)[1], delete=False).name
        subprocess.check_call([sys.executable, "-m", "fontTools.subset", src, f"--unicodes={unicodes}",
                               "--layout-features=*", "--no-hinting", "--desubroutinize", f"--output-file={tmp}"])
        src = tmp
    data = open(src, "rb").read()
    base = a.name or re.sub(r"[^0-9A-Za-z_]", "_", os.path.splitext(os.path.basename(a.font))[0])
    out = a.out or (base + (".cpp" if a.cpp else ".h"))
    arr = f"{base}_ttf"
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
    body = "\n".join(lines)
    with open(out, "w") as f:
        f.write(f"// Generated by FluxKit tools/ttf2h.py from {os.path.basename(a.font)} ({len(data)} bytes)\n")
        if a.cpp:
            f.write(f"extern const unsigned char {arr}[];\nextern const unsigned int {arr}_len;\n")
            f.write(f"const unsigned char {arr}[] = {{\n{body}\n}};\nconst unsigned int {arr}_len = {len(data)};\n")
        else:
            f.write("#pragma once\n")
            f.write(f"static const unsigned char {arr}[] = {{\n{body}\n}};\nstatic const unsigned int {arr}_len = {len(data)};\n")
    print(f"wrote {out} ({len(data)} bytes of font data)")

if __name__ == "__main__":
    main()
